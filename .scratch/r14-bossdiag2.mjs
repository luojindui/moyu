/** 聚焦诊断 v2：forceBoss 后轮询面板，再测 pointerdown 结算 */
import { spawn } from "node:child_process";
const CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const proc = spawn(CHROME, ["--headless=new", "--disable-gpu", "--no-sandbox", "--hide-scrollbars", "--mute-audio", "--no-first-run", "--disable-extensions", "--user-data-dir=/tmp/chrome-r14i-" + Date.now(), "--remote-debugging-port=9566", "about:blank"], { stdio: "ignore" });
for (let i = 0; i < 100; i++) { try { await fetch("http://127.0.0.1:9566/json/version"); break; } catch { await sleep(100); } }
const target = await fetch("http://127.0.0.1:9566/json/new?about:blank", { method: "PUT" }).then((r) => r.json());
const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let id = 0; const pending = new Map(); const logs = [];
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { const { resolve } = pending.get(m.id); pending.delete(m.id); resolve(m.result); return; } if (m.method === "Runtime.exceptionThrown") logs.push("EX " + (m.params.exceptionDetails?.exception?.description ?? m.params.exceptionDetails?.text ?? "")); if (m.method === "Runtime.consoleAPICalled" && m.params.type === "error") logs.push("ERR " + m.params.args.map(a => a.value ?? a.description).join(" ").slice(0, 300)); };
const send = (method, params = {}) => { const i = ++id; ws.send(JSON.stringify({ id: i, method, params })); return new Promise((resolve, reject) => pending.set(i, { resolve, reject })); };
const evalJs = async (expression) => { const r = await send("Runtime.evaluate", { expression, returnByValue: true, awaitPromise: true }); if (r.exceptionDetails) throw new Error(r.exceptionDetails.exception?.description ?? JSON.stringify(r.exceptionDetails)); return r.result.value; };
await send("Page.enable"); await send("Runtime.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 3, mobile: true, screenWidth: 390, screenHeight: 844 });
await send("Emulation.setTouchEmulationEnabled", { enabled: true, maxTouchPoints: 5 });
await send("Page.navigate", { url: "http://127.0.0.1:5173/" }); await sleep(3500);
await evalJs(`(()=>{const w=document.getElementById('welcome');if(w&&!w.classList.contains('hidden')){document.getElementById('welcome-ok').click();return true}return false})()`);
await sleep(300);
await evalJs(`window.__MOYU__.grant(1e9)`);
await sleep(300);
const openPanel = async () => { for (let t = 0; t < 40; t++) { const p = await evalJs(`(()=>{const r=document.getElementById('boss-choice');return r&&!r.classList.contains('hidden')?document.getElementById('boss-tell').textContent:null})()`); if (p) return p; await evalJs(`window.__MOYU__.forceBoss('choice')`); await sleep(150); } return null; };
const out = {};
out.tell = await openPanel();
const snap = () => evalJs(`(()=>({panel:!document.getElementById('boss-choice').classList.contains('hidden'),toast:(document.getElementById('dom-toast')||{}).textContent,fx:window.__MOYU__?.fxTexts?.().slice(-2),moyu:window.__MOYU__?.state?.moyu}))()`);
out.before = await snap();
out.buttons = await evalJs(`[...document.querySelectorAll('#boss-opts button')].map(b=>({id:b.dataset.choice,text:b.textContent}))`);
const correctOf = (t) => t.includes("脚步") ? "act-busy" : t.includes("盯着") ? "switch-screen" : "keep-slacking";
const choice = correctOf(out.tell ?? "");
out.choice = choice;
// 监听计数（捕获阶段）
await evalJs(`(()=>{window.__hits=0;const b=document.querySelector('#boss-opts button[data-choice="${choice}"]');if(b)b.addEventListener('pointerdown',()=>{window.__hits++},true);return !!b})()`);
await sleep(350);
await evalJs(`(()=>{const b=document.querySelector('#boss-opts button[data-choice="${choice}"]');b.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerId:1,isPrimary:true,pointerType:'touch'}));return true})()`);
await sleep(150);
out.after150 = await snap();
out.hits = await evalJs(`window.__hits`);
await sleep(3000);
out.after3s = await snap();
out.logs = logs.slice(0, 8);
console.log(JSON.stringify(out, null, 2));
proc.kill("SIGKILL"); process.exit(0);
